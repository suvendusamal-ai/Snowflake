-- Read-only verification of the approved immutable synthetic event set.
USE ROLE KPI_DATA_ENGINEER;
USE WAREHOUSE KPI_INTELLIGENCE_WH;
USE DATABASE KPI_INTELLIGENCE_DB;
USE SCHEMA RAW;

WITH verification AS (
    SELECT 1 AS CHECK_ID, 'SALES_EVENT_COUNT' AS CHECK_NAME,
           IFF((SELECT COUNT(*) FROM SALES_ORDER_EVENTS) = 8, 'PASS', 'FAIL') AS STATUS,
           OBJECT_CONSTRUCT('expected', 8, 'actual', (SELECT COUNT(*) FROM SALES_ORDER_EVENTS)) AS DETAILS
    UNION ALL
    SELECT 2, 'RECOGNITION_EVENT_COUNT',
           IFF((SELECT COUNT(*) FROM REVENUE_RECOGNITION_EVENTS) = 6, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected', 6, 'actual', (SELECT COUNT(*) FROM REVENUE_RECOGNITION_EVENTS))
    UNION ALL
    SELECT 3, 'SALES_EVENT_IDS_UNIQUE_AND_NOT_NULL',
           IFF((SELECT COUNT(*) FROM SALES_ORDER_EVENTS) = (SELECT COUNT(DISTINCT EVENT_ID) FROM SALES_ORDER_EVENTS)
               AND (SELECT COUNT_IF(EVENT_ID IS NULL) FROM SALES_ORDER_EVENTS) = 0, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('rows', (SELECT COUNT(*) FROM SALES_ORDER_EVENTS),
                            'distinct_ids', (SELECT COUNT(DISTINCT EVENT_ID) FROM SALES_ORDER_EVENTS))
    UNION ALL
    SELECT 4, 'RECOGNITION_EVENT_IDS_UNIQUE_AND_NOT_NULL',
           IFF((SELECT COUNT(*) FROM REVENUE_RECOGNITION_EVENTS) =
                   (SELECT COUNT(DISTINCT RECOGNITION_EVENT_ID) FROM REVENUE_RECOGNITION_EVENTS)
               AND (SELECT COUNT_IF(RECOGNITION_EVENT_ID IS NULL) FROM REVENUE_RECOGNITION_EVENTS) = 0,
               'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('rows', (SELECT COUNT(*) FROM REVENUE_RECOGNITION_EVENTS),
                            'distinct_ids', (SELECT COUNT(DISTINCT RECOGNITION_EVENT_ID) FROM REVENUE_RECOGNITION_EVENTS))
    UNION ALL
    SELECT 5, 'REQUIRED_FIELDS_PRESENT',
           IFF(
               (SELECT COUNT_IF(
                   ORDER_ID IS NULL OR ORDER_LINE_ID IS NULL OR CUSTOMER_ID IS NULL OR REGION IS NULL
                   OR EVENT_TYPE IS NULL OR EVENT_DATE IS NULL OR AMOUNT IS NULL OR CURRENCY IS NULL
                   OR SOURCE_SYSTEM IS NULL OR INGESTION_TIMESTAMP IS NULL
               ) FROM SALES_ORDER_EVENTS) = 0
               AND
               (SELECT COUNT_IF(
                   ORDER_ID IS NULL OR ORDER_LINE_ID IS NULL OR CUSTOMER_ID IS NULL OR REGION IS NULL
                   OR RECOGNITION_DATE IS NULL OR AMOUNT IS NULL OR CURRENCY IS NULL
                   OR RECOGNITION_TYPE IS NULL OR SOURCE_SYSTEM IS NULL OR INGESTION_TIMESTAMP IS NULL
               ) FROM REVENUE_RECOGNITION_EVENTS) = 0,
               'PASS', 'FAIL'
           ), OBJECT_CONSTRUCT('expected_missing_fields', 0)
    UNION ALL
    SELECT 6, 'APPROVED_EVENT_TYPES',
           IFF((SELECT COUNT_IF(EVENT_TYPE NOT IN ('BOOKING', 'CANCELLATION', 'AMENDMENT'))
                FROM SALES_ORDER_EVENTS) = 0
               AND (SELECT COUNT_IF(RECOGNITION_TYPE NOT IN ('FULL', 'PARTIAL', 'FINAL', 'ADJUSTMENT'))
                    FROM REVENUE_RECOGNITION_EVENTS) = 0, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('sales_types', ARRAY_CONSTRUCT('BOOKING', 'CANCELLATION', 'AMENDMENT'),
                            'recognition_types', ARRAY_CONSTRUCT('FULL', 'PARTIAL', 'FINAL', 'ADJUSTMENT'))
    UNION ALL
    SELECT 7, 'NON_ZERO_AMOUNTS',
           IFF((SELECT COUNT_IF(AMOUNT = 0) FROM SALES_ORDER_EVENTS) = 0
               AND (SELECT COUNT_IF(AMOUNT = 0) FROM REVENUE_RECOGNITION_EVENTS) = 0, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected_zero_amount_events', 0)
    UNION ALL
    SELECT 8, 'CANCELLATIONS_ARE_NEGATIVE',
           IFF((SELECT COUNT_IF(EVENT_TYPE = 'CANCELLATION' AND AMOUNT >= 0) FROM SALES_ORDER_EVENTS) = 0
               AND (SELECT COUNT_IF(EVENT_TYPE = 'CANCELLATION') FROM SALES_ORDER_EVENTS) >= 1,
               'PASS', 'FAIL'), OBJECT_CONSTRUCT('expected_rule', 'CANCELLATION amount < 0')
    UNION ALL
    SELECT 9, 'APPROVED_REGIONS',
           IFF((SELECT COUNT_IF(REGION NOT IN ('AMER', 'EMEA', 'APAC')) FROM SALES_ORDER_EVENTS) = 0
               AND (SELECT COUNT_IF(REGION NOT IN ('AMER', 'EMEA', 'APAC'))
                    FROM REVENUE_RECOGNITION_EVENTS) = 0, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('approved', ARRAY_CONSTRUCT('AMER', 'EMEA', 'APAC'))
    UNION ALL
    SELECT 10, 'O100_SAME_QUARTER_BOOKING_AND_RECOGNITION',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O100' AND EVENT_TYPE = 'BOOKING'
                                AND EVENT_DATE >= '2025-01-01'::DATE AND EVENT_DATE < '2025-04-01'::DATE
                                AND AMOUNT = 1000) FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O100'
                                    AND RECOGNITION_DATE >= '2025-01-01'::DATE
                                    AND RECOGNITION_DATE < '2025-04-01'::DATE AND AMOUNT = 1000)
                    FROM REVENUE_RECOGNITION_EVENTS) = 1, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O100', 'quarter', '2025-Q1')
    UNION ALL
    SELECT 11, 'O200_CROSS_QUARTER_RECOGNITION',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O200' AND EVENT_DATE >= '2025-01-01'::DATE
                                AND EVENT_DATE < '2025-04-01'::DATE AND AMOUNT = 1200)
                FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O200' AND RECOGNITION_DATE >= '2025-04-01'::DATE
                                    AND RECOGNITION_DATE < '2025-07-01'::DATE AND AMOUNT = 1200)
                    FROM REVENUE_RECOGNITION_EVENTS) = 1, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O200', 'booking_quarter', '2025-Q1', 'recognition_quarter', '2025-Q2')
    UNION ALL
    SELECT 12, 'O300_IMMUTABLE_BOOKING_AND_CANCELLATION',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O300' AND EVENT_ID = 'SE003'
                                AND EVENT_TYPE = 'BOOKING' AND AMOUNT = 800) FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O300' AND EVENT_ID = 'SE004'
                                    AND EVENT_TYPE = 'CANCELLATION' AND AMOUNT = -800)
                    FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O300') FROM SALES_ORDER_EVENTS) = 2, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O300', 'expected_events', ARRAY_CONSTRUCT('SE003', 'SE004'))
    UNION ALL
    SELECT 13, 'O300_HAS_NO_RECOGNITION',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O300') FROM REVENUE_RECOGNITION_EVENTS) = 0,
               'PASS', 'FAIL'), OBJECT_CONSTRUCT('order_id', 'O300', 'expected_recognition_events', 0)
    UNION ALL
    SELECT 14, 'O400_PARTIAL_RECOGNITION_ACROSS_QUARTERS',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O400' AND RECOGNITION_TYPE = 'PARTIAL'
                                AND RECOGNITION_DATE >= '2025-01-01'::DATE
                                AND RECOGNITION_DATE < '2025-04-01'::DATE AND AMOUNT = 800)
                FROM REVENUE_RECOGNITION_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O400' AND RECOGNITION_TYPE = 'FINAL'
                                    AND RECOGNITION_DATE >= '2025-04-01'::DATE
                                    AND RECOGNITION_DATE < '2025-07-01'::DATE AND AMOUNT = 1200)
                    FROM REVENUE_RECOGNITION_EVENTS) = 1, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O400', 'q1', 800, 'q2', 1200)
    UNION ALL
    SELECT 15, 'O500_IMMUTABLE_BOOKING_AND_AMENDMENT',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O500' AND EVENT_ID = 'SE006'
                                AND EVENT_TYPE = 'BOOKING' AND AMOUNT = 500) FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O500' AND EVENT_ID = 'SE007'
                                    AND EVENT_TYPE = 'AMENDMENT' AND AMOUNT = 200)
                    FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O500') FROM SALES_ORDER_EVENTS) = 2, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O500', 'expected_events', ARRAY_CONSTRUCT('SE006', 'SE007'))
    UNION ALL
    SELECT 16, 'O600_APAC_COVERAGE',
           IFF((SELECT COUNT_IF(ORDER_ID = 'O600' AND REGION = 'APAC') FROM SALES_ORDER_EVENTS) = 1
               AND (SELECT COUNT_IF(ORDER_ID = 'O600' AND REGION = 'APAC')
                    FROM REVENUE_RECOGNITION_EVENTS) = 1, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('order_id', 'O600', 'region', 'APAC')
    UNION ALL
    SELECT 17, 'Q1_SALES_BOOKINGS',
           IFF((SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
                WHERE EVENT_DATE >= '2025-01-01'::DATE AND EVENT_DATE < '2025-04-01'::DATE) = 4900,
               'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected', 4900, 'actual', (SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
               WHERE EVENT_DATE >= '2025-01-01'::DATE AND EVENT_DATE < '2025-04-01'::DATE))
    UNION ALL
    SELECT 18, 'Q1_RECOGNIZED_REVENUE',
           IFF((SELECT SUM(AMOUNT) FROM REVENUE_RECOGNITION_EVENTS
                WHERE RECOGNITION_DATE >= '2025-01-01'::DATE
                  AND RECOGNITION_DATE < '2025-04-01'::DATE) = 1800, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected', 1800, 'actual', (SELECT SUM(AMOUNT)
               FROM REVENUE_RECOGNITION_EVENTS WHERE RECOGNITION_DATE >= '2025-01-01'::DATE
               AND RECOGNITION_DATE < '2025-04-01'::DATE))
    UNION ALL
    SELECT 19, 'Q2_SALES_BOOKINGS',
           IFF((SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
                WHERE EVENT_DATE >= '2025-04-01'::DATE AND EVENT_DATE < '2025-07-01'::DATE) = 900,
               'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected', 900, 'actual', (SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
               WHERE EVENT_DATE >= '2025-04-01'::DATE AND EVENT_DATE < '2025-07-01'::DATE))
    UNION ALL
    SELECT 20, 'Q2_RECOGNIZED_REVENUE',
           IFF((SELECT SUM(AMOUNT) FROM REVENUE_RECOGNITION_EVENTS
                WHERE RECOGNITION_DATE >= '2025-04-01'::DATE
                  AND RECOGNITION_DATE < '2025-07-01'::DATE) = 4000, 'PASS', 'FAIL'),
           OBJECT_CONSTRUCT('expected', 4000, 'actual', (SELECT SUM(AMOUNT)
               FROM REVENUE_RECOGNITION_EVENTS WHERE RECOGNITION_DATE >= '2025-04-01'::DATE
               AND RECOGNITION_DATE < '2025-07-01'::DATE))
    UNION ALL
    SELECT 21, 'QUARTERLY_KPIS_DIFFER',
           IFF(
               (SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
                WHERE EVENT_DATE >= '2025-01-01'::DATE AND EVENT_DATE < '2025-04-01'::DATE)
               <>
               (SELECT SUM(AMOUNT) FROM REVENUE_RECOGNITION_EVENTS
                WHERE RECOGNITION_DATE >= '2025-01-01'::DATE AND RECOGNITION_DATE < '2025-04-01'::DATE)
               AND
               (SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
                WHERE EVENT_DATE >= '2025-04-01'::DATE AND EVENT_DATE < '2025-07-01'::DATE)
               <>
               (SELECT SUM(AMOUNT) FROM REVENUE_RECOGNITION_EVENTS
                WHERE RECOGNITION_DATE >= '2025-04-01'::DATE AND RECOGNITION_DATE < '2025-07-01'::DATE),
               'PASS', 'FAIL'
           ), OBJECT_CONSTRUCT('q1_sales', 4900, 'q1_revenue', 1800, 'q2_sales', 900, 'q2_revenue', 4000)
    UNION ALL
    SELECT 22, 'H1_TOTALS_RECONCILE',
           IFF((SELECT SUM(AMOUNT) FROM SALES_ORDER_EVENTS
                WHERE EVENT_DATE >= '2025-01-01'::DATE AND EVENT_DATE < '2025-07-01'::DATE) = 5800
               AND (SELECT SUM(AMOUNT) FROM REVENUE_RECOGNITION_EVENTS
                    WHERE RECOGNITION_DATE >= '2025-01-01'::DATE
                      AND RECOGNITION_DATE < '2025-07-01'::DATE) = 5800,
               'PASS', 'FAIL'), OBJECT_CONSTRUCT('expected_sales', 5800, 'expected_revenue', 5800)
    UNION ALL
    SELECT 23, 'NO_UNEXPECTED_EVENT_IDS_OR_ROWS',
           IFF((SELECT COUNT_IF(EVENT_ID NOT IN
                    ('SE001', 'SE002', 'SE003', 'SE004', 'SE005', 'SE006', 'SE007', 'SE008'))
                FROM SALES_ORDER_EVENTS) = 0
               AND (SELECT COUNT(*) FROM SALES_ORDER_EVENTS) = 8
               AND (SELECT COUNT_IF(RECOGNITION_EVENT_ID NOT IN
                    ('RE001', 'RE002', 'RE003', 'RE004', 'RE005', 'RE006'))
                    FROM REVENUE_RECOGNITION_EVENTS) = 0
               AND (SELECT COUNT(*) FROM REVENUE_RECOGNITION_EVENTS) = 6,
               'PASS', 'FAIL'), OBJECT_CONSTRUCT('expected_sales_rows', 8, 'expected_revenue_rows', 6)
)
SELECT CHECK_ID, CHECK_NAME, STATUS, DETAILS
FROM verification
ORDER BY CHECK_ID;
