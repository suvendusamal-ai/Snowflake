USE ROLE KPI_DATA_ENGINEER;
USE WAREHOUSE KPI_INTELLIGENCE_WH;
USE DATABASE KPI_INTELLIGENCE_DB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS SALES_ORDER_EVENTS (
    EVENT_ID VARCHAR NOT NULL,
    ORDER_ID VARCHAR NOT NULL,
    ORDER_LINE_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL,
    EVENT_TYPE VARCHAR NOT NULL,
    EVENT_DATE DATE NOT NULL,
    AMOUNT NUMBER(18, 2) NOT NULL,
    CURRENCY VARCHAR(3) NOT NULL,
    SOURCE_SYSTEM VARCHAR NOT NULL,
    INGESTION_TIMESTAMP TIMESTAMP_NTZ NOT NULL
)
COMMENT = 'Immutable commercial booking, cancellation, and amendment events';

CREATE TABLE IF NOT EXISTS REVENUE_RECOGNITION_EVENTS (
    RECOGNITION_EVENT_ID VARCHAR NOT NULL,
    ORDER_ID VARCHAR NOT NULL,
    ORDER_LINE_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL,
    RECOGNITION_DATE DATE NOT NULL,
    AMOUNT NUMBER(18, 2) NOT NULL,
    CURRENCY VARCHAR(3) NOT NULL,
    RECOGNITION_TYPE VARCHAR NOT NULL,
    SOURCE_SYSTEM VARCHAR NOT NULL,
    INGESTION_TIMESTAMP TIMESTAMP_NTZ NOT NULL
)
COMMENT = 'Immutable revenue recognition and recognition-adjustment events';
