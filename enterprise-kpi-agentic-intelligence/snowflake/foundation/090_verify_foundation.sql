-- Verification role: KPI_PLATFORM_ADMIN. This script is read-only.
USE ROLE KPI_PLATFORM_ADMIN;
USE WAREHOUSE KPI_INTELLIGENCE_WH;

SHOW ROLES;
SELECT
    'APPROVED_ROLE_COUNT' AS check_name,
    IFF(COUNT_IF("name" IN (
        'KPI_PLATFORM_ADMIN', 'KPI_DATA_ENGINEER', 'KPI_SEMANTIC_ENGINEER',
        'KPI_AI_BUILDER', 'KPI_AI_RUNTIME', 'KPI_EXECUTIVE', 'KPI_AUDITOR'
    )) = 7, 'PASS', 'FAIL') AS status,
    COUNT_IF("name" IN (
        'KPI_PLATFORM_ADMIN', 'KPI_DATA_ENGINEER', 'KPI_SEMANTIC_ENGINEER',
        'KPI_AI_BUILDER', 'KPI_AI_RUNTIME', 'KPI_EXECUTIVE', 'KPI_AUDITOR'
    )) AS observed_project_roles
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW GRANTS OF ROLE KPI_DATA_ENGINEER;
SELECT 'KPI_DATA_ENGINEER_PARENT' AS check_name,
       IFF(COUNT_IF("granted_to" = 'ROLE' AND "grantee_name" = 'KPI_PLATFORM_ADMIN') = 1, 'PASS', 'FAIL') AS status
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW GRANTS OF ROLE KPI_SEMANTIC_ENGINEER;
SELECT 'KPI_SEMANTIC_ENGINEER_PARENT' AS check_name,
       IFF(COUNT_IF("granted_to" = 'ROLE' AND "grantee_name" = 'KPI_PLATFORM_ADMIN') = 1, 'PASS', 'FAIL') AS status
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

