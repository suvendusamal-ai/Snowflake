/*
Purpose:
  Create the DBT_DEMO_DEV.RAW source schema and load reproducible demo data.

Execution role:
  ACCOUNTADMIN for this demonstration.
  In production, use a dedicated ingestion/platform role.

Warning:
  CREATE OR REPLACE resets the four demo tables.
*/

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS DBT_DEMO_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Warehouse for native Snowflake dbt project execution';

USE WAREHOUSE DBT_DEMO_WH;

CREATE DATABASE IF NOT EXISTS DBT_DEMO_DEV
    COMMENT = 'Development database for the Snowflake dbt demonstration';

CREATE SCHEMA IF NOT EXISTS DBT_DEMO_DEV.RAW
    COMMENT = 'Source-shaped records loaded independently from dbt';

USE DATABASE DBT_DEMO_DEV;
USE SCHEMA RAW;

